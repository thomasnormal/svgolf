"""Generates reference/keccak_round.sv: the textbook round, written the way the sv_comb tactics
want it (flat top, continuous assigns, 2-D packed lane arrays, localparam rotation amounts,
doubled-vector rotation so a rotation by 0 needs no special case).  Lane i = x + 5*y.

  python3 gen_ref.py [--chi xor3]   # chi as  a ^ c ^ (b & c)  instead of  a ^ (~b & c)
"""
import sys
from oracle import RHO

chi_xor3 = "--chi" in sys.argv and sys.argv[sys.argv.index("--chi") + 1] == "xor3"
L = []
w = L.append
w("// keccak_round: one round of Keccak-p on 25 lanes of W bits (FIPS 202: iota o chi o pi o rho o theta).")
w("// DRAFT reference for the proposed svGolf task `keccak_round`; generated by gen_ref.py, not hand-edited.")
w("module keccak_round #(parameter int W = 16) (")
w("  input  logic [24:0][W-1:0] a,    // lane i = x + 5*y, bit z of lane i is flat bit W*i + z")
w("  input  logic [W-1:0]       rc,   // round constant (iota)")
w("  output logic [24:0][W-1:0] y")
w(");")
w("  // rho rotation amounts, reduced mod W (FIPS 202: offsets (t+1)(t+2)/2 are taken mod W)")
for i in range(25):
    x, yy = i % 5, i // 5
    w(f"  localparam integer R{i} = {RHO[x][yy]} % W;")
w("  logic [4:0][W-1:0]    c, d;")
w("  logic [4:0][2*W-1:0]  cc;          // {c, c}: rotate-left by R is cc[2W-1-R : W-R]")
w("  logic [24:0][W-1:0]   t;           // after theta")
w("  logic [24:0][2*W-1:0] tt;          // {t, t}")
w("  logic [24:0][W-1:0]   b;           // after rho and pi")
for x in range(5):
    w(f"  assign c[{x}]  = a[{x}] ^ a[{x+5}] ^ a[{x+10}] ^ a[{x+15}] ^ a[{x+20}];")
    w(f"  assign cc[{x}] = {{c[{x}], c[{x}]}};")
for x in range(5):
    w(f"  assign d[{x}]  = c[{(x+4)%5}] ^ cc[{(x+1)%5}][2*W-1-R1 : W-R1];")
for i in range(25):
    w(f"  assign t[{i}]  = a[{i}] ^ d[{i%5}];")
    w(f"  assign tt[{i}] = {{t[{i}], t[{i}]}};")
for i in range(25):
    x, yy = i % 5, i // 5
    j = yy + 5 * ((2 * x + 3 * yy) % 5)          # pi: lane (x,y) moves to (y, 2x+3y)
    w(f"  assign b[{j}]  = tt[{i}][2*W-1-R{i} : W-R{i}];")
for yy in range(5):
    for x in range(5):
        i = x + 5 * yy; i1 = (x + 1) % 5 + 5 * yy; i2 = (x + 2) % 5 + 5 * yy
        rhs = f"b[{i}] ^ b[{i2}] ^ (b[{i1}] & b[{i2}])" if chi_xor3 else f"b[{i}] ^ (~b[{i1}] & b[{i2}])"
        if i == 0: rhs += " ^ rc"
        w(f"  assign y[{i}] = {rhs};")
w("endmodule")
print("\n".join(L))
