#!/usr/bin/env python3
"""X6 step 2: write the batched Lean files (one slot run each) that run the multi-point cross-check over every extracted design.

    python3 x6_lean.py --index OUT/index.json --lean OUT/X6Batch [--max-mb 40]
    (then, from the repository root, through the machine's Lean slot, one acquisition per batch file:)
    $SLOT lake env lean OUT/X6Batch_<k>.lean > OUT/lean_<k>.tsv

For each design with an envelope and a sidecar, one `#eval` prints one tab-separated line per probe entry:
    X6 <id> <label> <verdict kind> <rendered verdict>
where the verdict is `LeanModels.Sv.probeReportString`'s (Probe2.lean): `agree` (the envelope brought to the point and
slang's own extraction at the point instantiate to equal designs, and slang's resolved metadata at the point - parameter
values, localparams, declared widths, generate counts - agrees with the Lean elaboration there), `differ` (a silent
default-point fold), `unconfirmed` (equal except where one side is loud), `metaDiffer` (Lean's elaboration at the point
disagrees with slang's metadata), `frontendRejects` (slang rejects the point), `refused` (one side does not instantiate).
A design whose files cannot be read or parsed prints `parseError`. Nothing else is run; no theorem is stated.
"""
import argparse
import json
import os


HEADER = '''import LeanModels.Sv.Ingest2
/-! X6 batch (generated by x6_lean.py; not part of the build). One `#eval` per design. -/
open LeanModels.Sv

namespace X6

def kindOf : ProbeVerdict → String
  | .agree => "agree"
  | .differ _ => "differ"
  | .unconfirmed _ => "unconfirmed"
  | .metaDiffer _ => "metaDiffer"
  | .frontendRejects _ => "frontendRejects"
  | .refused _ => "refused"

def clean (s : String) : String :=
  String.mk (((s.replace "\\n" " ").replace "\\t" " ").toList.take 600)

def one (id envPath sidePath : String) : IO Unit := do
  try
    let envText ← IO.FS.readFile envPath
    let prText ← IO.FS.readFile sidePath
    match probeReportString envText prText with
    | .ok rep =>
        if rep.isEmpty then IO.println s!"X6\\t{id}\\t-\\tempty\\t"
        for (l, v) in rep do
          IO.println s!"X6\\t{id}\\t{clean l}\\t{kindOf v}\\t{clean v.render}"
    | .error e => IO.println s!"X6\\t{id}\\t-\\tparseError\\t{clean e}"
  catch e => IO.println s!"X6\\t{id}\\t-\\tioError\\t{clean (toString e)}"

end X6
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--index", required=True)
    ap.add_argument("--lean", required=True, help="output stem: STEM_<k>.lean, one file per batch")
    ap.add_argument("--max-mb", type=float, default=40.0, help="JSON megabytes per batch file (one slot run each)")
    a = ap.parse_args()
    rows = [r for r in json.load(open(a.index)) if r.get("envelope") and r.get("sidecar")]
    size = lambda r: os.path.getsize(r["envelope"]) + os.path.getsize(r["sidecar"])  # noqa: E731
    rows.sort(key=size)
    batches, cur, acc = [], [], 0
    for r in rows:
        if cur and acc + size(r) > a.max_mb * 1e6:
            batches.append(cur)
            cur, acc = [], 0
        cur.append(r)
        acc += size(r)
    if cur:
        batches.append(cur)
    for k, b in enumerate(batches):
        out = [HEADER]
        for r in b:
            out.append("#eval X6.one %s %s %s" % (json.dumps(r["id"]), json.dumps(r["envelope"]),
                                                  json.dumps(r["sidecar"])))
        open("%s_%d.lean" % (a.lean, k), "w").write("\n".join(out) + "\n")
        print("%s_%d.lean: %d designs, %.1f MB" % (a.lean, k, len(b), sum(size(r) for r in b) / 1e6))


if __name__ == "__main__":
    main()
