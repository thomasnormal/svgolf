#!/usr/bin/env python3.12
"""Derive score/ge_seq.json, the GE table of the clocked scoring flow (svgolf_seq.ys), from the PINNED sky130 liberty.

What it derives (PLAN4 C7; WP-X1, design/ppa/sky130.md):
  * DFF_P, the price of the flop `dfflegalize` leaves ($_DFF_P_, a plain rising-edge D flip-flop), as the sky130_fd_sc_hd
    cell a sky130 mapping uses for it, dfxtp_1, over nand2_1, in NAND2 gate equivalents rounded to milli-GE (the unit
    score.py adds up). sky130_fd_sc_hd has no synchronous-reset flop: a synchronous reset is dfxtp_1 plus logic, and the
    flow keeps that logic as priced gates.
  * the per-cycle REGISTER OVERHEAD, dfxtp_1's clock-to-Q plus its setup time, in nand2_1 delays. It is reported, and
    included in a period only on request (`score.py --seq --reg-overhead`): whether it counts is the maintainers' to rule.
    Conditions are the pinned A0' timing setup (score/ppa_pins.json): every input transition pi_slew_ps (CLK and D for
    the flop, A/B for the nand2), every output load po_load_ff (Q and Y); a delay is the worse of the rise and fall
    tables, over every arc; setup is the worse of the setup_rising rise/fall constraints.
The combinational weights are copied VERBATIM from score/ge.json (the legacy table, beside which the flop is priced).

  python3.12 score/derive_seq_prices.py            # write score/ge_seq.json
  python3.12 score/derive_seq_prices.py --check    # exit 1 unless score/ge_seq.json is what the liberty gives
"""
import argparse
import json
import os
import sys
from decimal import Decimal, ROUND_HALF_EVEN

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
import ppa  # noqa: E402

GE_COMB = os.path.join(HERE, "ge.json")
GE_SEQ = os.path.join(HERE, "ge_seq.json")
FLOP, UNIT = "dfxtp_1", "nand2_1"


def cell_group(lib, name):
    """The parsed liberty group of cell `name` (any kind of cell: ppa.Cell admits combinational arcs only)."""
    text, start = lib._text, lib._start[name]
    depth = 0
    for m in ppa._BRACE_RE.finditer(text, text.index("{", start)):
        depth += 1 if m.group(0) == "{" else -1 if m.group(0) == "}" else 0
        if depth == 0:
            return ppa._parse_group_text(text[start:m.end()])
    raise ppa.PpaError(f"liberty: unbalanced braces in cell {name}")


def worst(timing, kinds, x1, x2, what):
    vals = []
    for k in kinds:
        found = timing.find(k)
        if len(found) != 1:
            raise ppa.PpaError(f"{what}: expected one {k} table, found {len(found)}")
        vals.append(ppa.Table(found[0], f"{what} {k}").at(x1, x2))
    return max(vals)


def derive(lib, pins):
    p = pins.prefix
    slew, load = pins.pi_slew_ns, pins.po_load_pf
    flop = cell_group(lib, p + FLOP)
    area_flop = ppa._area_e4(flop.attrs.get("area"), FLOP)
    area_unit = lib.cell(p + UNIT).area_e4
    price = (Decimal(area_flop) / Decimal(area_unit)).quantize(Decimal("0.001"), ROUND_HALF_EVEN)
    clk_q = setup = None
    for pin in flop.find("pin"):
        for t in pin.find("timing"):
            tt = t.attrs.get("timing_type")
            if pin.args[0] == "Q" and tt == "rising_edge":
                clk_q = worst(t, ("cell_rise", "cell_fall"), slew, load, f"{FLOP} CLK->Q")
            elif pin.args[0] == "D" and tt == "setup_rising":
                setup = worst(t, ("rise_constraint", "fall_constraint"), slew, slew, f"{FLOP} setup")
    if clk_q is None or setup is None:
        raise ppa.PpaError(f"liberty: {FLOP} has no rising_edge CLK->Q arc or no setup_rising constraint")
    unit = max(a.tbl[k].at(slew, load) for arcs in lib.cell(p + UNIT).arcs.values()
               for a in arcs for k in ("cell_rise", "cell_fall"))
    with open(GE_COMB) as fh:
        comb = json.load(fh)
    out = {"_comment": "GE table of the CLOCKED flow (score/svgolf_seq.ys): the legacy combinational weights of "
                       "score/ge.json, verbatim, plus the flop. GENERATED by score/derive_seq_prices.py from the "
                       "pinned sky130 liberty; do not edit by hand (a change here is a change to every sequential "
                       "score). Keys starting with _ are not prices."}
    out.update({k: v for k, v in comb.items() if not k.startswith("_")})
    out["DFF_P"] = float(price)
    ns = lambda x: round(x * 1000, 3)  # noqa: E731  ns -> ps, 3 decimals
    out["_derivation"] = {
        "liberty_sha256": lib.sha256, "ppa_pins_sha256": pins.sha256, "ge_json_sha256": ppa.sha256_file(GE_COMB),
        "DFF_P": {"cell": p + FLOP, "area_um2": area_flop / 10000, "per": p + UNIT, "per_area_um2": area_unit / 10000,
                  "rounding": "ratio to 0.001, half-even"}}
    out["_reg_overhead"] = {
        "clk_to_q_ps": ns(clk_q), "setup_ps": ns(setup), "nand2_delay_ps": ns(unit),
        "nand2_delays": round((clk_q + setup) / unit, 3),
        "conditions": f"input transitions {pins.pi_slew_ns * 1000:g} ps, output loads {pins.po_load_pf * 1000:g} fF; "
                      "worst of rise/fall over every arc",
        "included": "only with score.py --seq --reg-overhead (ceil of nand2_delays added to the depth); "
                    "not ruled"}
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--liberty")
    args = ap.parse_args(argv)
    pins = ppa.Pins()
    try:
        lib = ppa.Liberty(ppa.find_liberty(args.liberty, pins), pins)
        text = json.dumps(derive(lib, pins), indent=2) + "\n"
    except ppa.PpaError as e:
        print(f"derive_seq_prices: {e}", file=sys.stderr)
        return 2
    if args.check:
        with open(GE_SEQ) as fh:
            ok = fh.read() == text
        print("ge_seq.json " + ("matches the liberty" if ok else "DIFFERS from what the liberty gives"))
        return 0 if ok else 1
    with open(GE_SEQ, "w") as fh:
        fh.write(text)
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
