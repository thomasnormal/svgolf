"""The committed schematic and critical-path data of the record pages (site/schematics/, written by
site/gen_schematics.py), checked against the repository without any tool; and, where the tools are installed,
that the generator gives the same bytes twice and the committed bytes.

    python3 -m unittest discover -s svgolf/tests/site      (from the lean-surfaces root)

The determinism test needs the pinned Yosys, the pinned liberty, Node and netlistsvg 1.0.2 (the install note is in
site/gen_schematics.py's docstring; point $SVGOLF_NETLISTSVG at its node_modules); without them it is skipped.
"""

import hashlib
import importlib.util
import json
import os
import re
import shutil
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SVGOLF = os.path.dirname(os.path.dirname(HERE))
SITE = os.path.join(SVGOLF, "site")
OUT = os.path.join(SITE, "schematics")


def load(name, path):
    sys.path.insert(0, SITE)
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


gen = load("svgolf_gen_schematics", os.path.join(SITE, "gen_schematics.py"))


def read_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def sha(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def records():
    out = []
    data = os.path.join(SVGOLF, "leaderboard", "data")
    for t in sorted(os.listdir(data)):
        for f in sorted(os.listdir(os.path.join(data, t))):
            if f.endswith(".json"):
                out.append(read_json(os.path.join(data, t, f)))
    return out


class CommittedTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tasks = gen.listed_tasks()
        cls.display = read_json(gen.DISPLAY)
        cls.data = {}
        for t in cls.tasks:
            for d in gen.designs(t):
                p = os.path.join(OUT, t, gen.key_of(d["sha256"]) + ".json")
                cls.data[(t, d["sha256"])] = (d, read_json(p) if os.path.isfile(p) else None)

    def test_the_check_passes(self):
        """Every design that gets a page has its data, every drawn one its SVG with the recorded hash; no stray file;
        no path, tool banner or script in a drawing; the total under the budget."""
        self.assertEqual(gen.check(self.tasks), [])

    def test_every_listed_task_has_a_display_instance(self):
        self.assertEqual(sorted(self.tasks), sorted(self.display["tasks"]))
        for t in self.tasks:
            task = read_json(os.path.join(SVGOLF, "tasks", t, "task.json"))
            names = [p["name"] for p in task.get("parameters", [])]
            self.assertEqual(sorted(self.display["tasks"][t]["params"]), sorted(names), t)

    def test_total_size_is_within_the_budget(self):
        total = sum(os.path.getsize(os.path.join(OUT, t, f)) for t in self.tasks
                    for f in os.listdir(os.path.join(OUT, t)) if f.endswith(".svg"))
        self.assertLessEqual(total, 5_000_000)
        self.assertEqual(self.display["max_total_bytes"], 5_000_000)

    def test_drawings_read_the_page_colours_and_carry_nothing_of_the_machine(self):
        """A drawing is inline on its page: its style is scoped to svg.sch and every colour is a site token (a light
        fallback after it); no baked colour attribute, no path, no Yosys banner, no script."""
        n = 0
        for t in self.tasks:
            for f in sorted(os.listdir(os.path.join(OUT, t))):
                if not f.endswith(".svg"):
                    continue
                n += 1
                with self.subTest(svg=f"{t}/{f}"):
                    text = open(os.path.join(OUT, t, f), encoding="utf-8").read()
                    self.assertTrue(text.startswith('<svg xmlns="http://www.w3.org/2000/svg" class="sch" viewBox="0 0 '))
                    style = re.search(r"<style>(.*?)</style>", text, re.S).group(1)
                    for rule in re.findall(r"([^{}]+)\{", style):
                        self.assertTrue(all(sel.strip().startswith("svg.sch") for sel in rule.split(",")), rule)
                    self.assertEqual(re.findall(r"#[0-9a-fA-F]{3,6}\b", re.sub(r"var\(--[a-z0-9-]+,#[0-9a-fA-F]+\)", "", style)), [])
                    body = text.replace(style, "")
                    self.assertNotRegex(body, r"(fill|stroke|color)\s*[:=]\s*[\"']?#")
                    self.assertNotRegex(body, r"\bs:[a-z]+=|xmlns:s=")
                    for bad in ("/Users/", "/home/", "/private/", "/tmp/", "Generated by Yosys", "<script", "netlistsvg.js"):
                        self.assertNotIn(bad, text)
        self.assertGreater(n, 0)

    def test_display_instances_are_display_json_and_drawn_or_explained(self):
        for (t, s), (d, data) in sorted(self.data.items()):
            with self.subTest(task=t, design=d["src"]):
                self.assertIsNotNone(data)
                disp = data["display"]
                self.assertEqual(disp["params"], self.display["tasks"][t]["params"])
                if disp.get("drawn"):
                    piece = self.display["tasks"][t]["draw"] == "critical" or disp["cells_sky130"] > self.display["max_full_cells"]
                    self.assertEqual(disp["drawn"], "critical" if piece else "full")
                    if disp["drawn"] == "full":
                        self.assertEqual(disp["drawn_cells"], disp["cells_sky130"])
                    else:
                        self.assertEqual(disp["drawn_cells"], disp["critical"]["cells"])
                    svg = os.path.join(OUT, t, gen.key_of(s) + ".svg")
                    self.assertEqual(sha(svg), disp["svg_sha256"])
                    text = open(svg, encoding="utf-8").read()
                    self.assertEqual(len(re.findall(r'class="c( crit)?"', text)), disp["drawn_cells"])   # a group per cell
                    # the critical path is marked: its cells in a whole drawing, its nets in both kinds
                    cells = {n["inst"] for n in disp["path"] if n.get("inst")}
                    marked = set(re.findall(r'class="c crit" data-inst="([^"]+)"', text))
                    self.assertEqual(marked, cells if disp["drawn"] == "full" else set())
                    if len(disp["path"]) > 1:
                        self.assertRegex(text, r'<line [^>]*class="crit"')
                else:
                    self.assertTrue(disp.get("reason"))

    def test_scored_numbers_are_the_records_and_the_goldens(self):
        """The scored block is ppa.py at the scoring point: equal to the record's own ppa block (same weighing) and to
        the golden of score/tests/ppa/ where the design has one, bit for bit; its path ends at the delay."""
        pins = read_json(os.path.join(SVGOLF, "score", "ppa_pins.json"))
        designs = read_json(os.path.join(SVGOLF, "score", "tests", "ppa", "designs.json"))["designs"]
        gold = read_json(os.path.join(SVGOLF, "score", "tests", "ppa", "expected_ppa.json"))
        golden = {}
        for g in designs:
            task = read_json(os.path.join(SVGOLF, "tasks", g["task"], "task.json"))
            if g["name"] in gold["designs"] and (g.get("params") or {}) == task["scoring"]["params"]:
                golden[(g["task"], sha(os.path.join(SVGOLF, g["src"])))] = gold["designs"][g["name"]]
        recs = {}
        for r in records():
            if isinstance(r.get("ppa"), dict) and r["ppa"].get("ppa_version") == pins["ppa_version"]:
                recs.setdefault((r["task"], r["files"]["sv"]["sha256"]), []).append(r)
        compared = 0
        for (t, s), (d, data) in sorted(self.data.items()):
            sc = data["scored"]
            with self.subTest(task=t, design=d["src"]):
                self.assertEqual(sc["ppa_version"], pins["ppa_version"])
                for r in recs.get((t, s), []):
                    compared += 1
                    for k in ("area_e4um2_sky130", "delay_ps_sky130", "cells_sky130", "cell_hist_sky130", "unit_depth",
                              "netlist_sha256", "critical"):
                        self.assertEqual(sc[k], r["ppa"][k], k)
                    self.assertEqual(sc["repair"]["netlist_sha256"], r["ppa"]["repair"]["netlist_sha256"])
                g = golden.get((t, s))
                if g and g.get("area_e4um2") is not None:
                    compared += 1
                    self.assertEqual((sc["area_e4um2_sky130"], sc["delay_ps_sky130"], sc["cells_sky130"]),
                                     (g["area_e4um2"], g["delay_ps"], g["cells"]))
                path = sc["path"]
                self.assertEqual(sum(1 for n in path if n["inst"]), sc["critical"]["cells"])
                if not sc.get("sequential"):
                    self.assertLessEqual(abs(path[-1]["arrival_ps"] - sc["delay_ps_sky130"]), 0.55)   # 0.1 ps, then 1 ps
                self.assertEqual([n["arrival_ps"] for n in path], sorted(n["arrival_ps"] for n in path))
                areas = data["cell_area_e4um2"]
                self.assertEqual(sum(areas[c] * k for c, k in sc["cell_hist_sky130"].items()), sc["area_e4um2_sky130"])
        self.assertGreaterEqual(compared, 10)

    def test_the_skin_draws_every_cell_the_netlists_use(self):
        skin = open(gen.SKIN, encoding="utf-8").read()
        for kind, (symbol, _) in gen.CELLS.items():
            self.assertIn(f's:type="{symbol}"', skin, kind)
        self.assertIn("MIT", skin)
        seen = {c.rsplit("_", 1)[0] for _, data in self.data.values() for c in data["scored"]["cell_hist_sky130"]}
        self.assertLessEqual(seen, set(gen.CELLS))


def tools_missing():
    nsvg = os.environ.get("SVGOLF_NETLISTSVG")
    if not nsvg or not os.path.isdir(nsvg):
        return "SVGOLF_NETLISTSVG is not set to netlistsvg's node_modules"
    for exe in ("node", "yosys"):
        if not shutil.which(exe):
            return f"{exe} is not on PATH"
    if not os.path.isfile(os.path.join(SVGOLF, "score", "lib", "sky130_fd_sc_hd__tt_025C_1v80.lib")) \
            and not os.environ.get("SVGOLF_SKY130_LIB"):
        return "the pinned liberty is not fetched"
    return None


@unittest.skipIf(tools_missing(), tools_missing() or "")
class DeterminismTest(unittest.TestCase):
    def test_two_runs_give_the_committed_bytes(self):
        """The smallest designs, drawn whole and as a critical path: two runs byte-identical, and equal to the
        committed files."""
        display = read_json(gen.DISPLAY)
        nsvg = gen.node_tool(os.environ["SVGOLF_NETLISTSVG"])
        tools = {"netlistsvg": gen.NETLISTSVG, "elkjs": gen.ELKJS, "yosys": gen.yosys_version(),
                 "skin_sha256": sha(gen.SKIN)}
        for task in ("_example", "aes_sbox"):
            d = min(gen.designs(task), key=lambda d: os.path.getsize(os.path.join(SVGOLF, d["src"])))
            cfg = dict(display["tasks"][task], max_full_cells=display["max_full_cells"])
            runs = [gen.one_design(task, d, cfg, nsvg=nsvg, tools=tools, budget_left=10 ** 9) for _ in range(2)]
            with self.subTest(task=task, design=d["src"]):
                self.assertEqual(gen.json_text(runs[0][0]), gen.json_text(runs[1][0]))
                self.assertEqual(runs[0][1], runs[1][1])
                k = gen.key_of(d["sha256"])
                with open(os.path.join(OUT, task, k + ".json"), encoding="utf-8") as fh:
                    self.assertEqual(gen.json_text(runs[0][0]), fh.read())
                with open(os.path.join(OUT, task, k + ".svg"), encoding="utf-8") as fh:
                    self.assertEqual(runs[0][1], fh.read())


if __name__ == "__main__":
    unittest.main()
